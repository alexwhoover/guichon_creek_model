# Build Raven forcing file data/met_daily.rvt from the gap-filled Lornex record,
# and print the monthly normals needed for the gauge block in hbvec.rvt
# (PET_FROMMONTHLY needs :MonthlyAveTemperature and :MonthlyAveEvaporation).
#
# Input : data/processed/1123469_HighlandValleyLornex_filled_daily.csv  (from fill_met_lornex.R)
# Output: data/met_daily.rvt
#         data/processed/lornex_monthly_normals.csv
#
# Monthly normals are computed over the model period NORM_START..NORM_END.
#   Temperature : mean of (Tmax + Tmin) / 2
#   PET         : Hargreaves (1985), from Tmax, Tmin and extraterrestrial
#                 radiation at the gauge latitude; mm/d
#
# Usage (from Raven/HBVEC_Model):  Rscript data/scripts/write_met_rvt.R
# Then copy the printed :MonthlyAve* lines into the gauge block in hbvec.rvt.

Sys.setenv(TZ = "America/Vancouver")

LAT        <- 50.4667          # Highland Valley Lornex, deg N
NORM_START <- as.Date("1982-10-01")
NORM_END   <- as.Date("2011-09-30")

d <- read.csv("data/processed/1123469_HighlandValleyLornex_filled_daily.csv")
d$date <- as.Date(d$date)
stopifnot(!anyNA(d[, c("TEMP_MAX", "TEMP_MIN", "PRECIP")]),
          all(diff(d$date) == 1))

# ---- :MultiData forcing file -------------------------------------------------
n   <- nrow(d)
src <- table(c(d$TEMP_MAX_SRC, d$TEMP_MIN_SRC, d$PRECIP_SRC) != "OBS")
con <- file("data/met_daily.rvt", "w")
writeLines(c(
  "# Daily forcing: ECCC HIGHLAND VALLEY LORNEX (Climate ID 1123469)",
  "#   50.4667 N, 121.0167 W, 1268 m",
  "# Gaps filled from KAMLOOPS A (1163780) by monthly linear scaling;",
  "#   see data/scripts/fill_met_lornex.R; the SRC columns in",
  "#   data/processed/1123469_HighlandValleyLornex_filled_daily.csv show which values were filled.",
  "# Generated by data/scripts/write_met_rvt.R",
  "# PRECIP = total precipitation (rain + snow water equivalent), mm/d.",
  ":MultiData",
  sprintf(" %s 00:00:00  1.0  %d", format(d$date[1]), n),
  ":Parameters  TEMP_DAILY_MAX  TEMP_DAILY_MIN  PRECIP",
  ":Units       C               C               mm/d"), con)
writeLines(sprintf(" %6.1f  %6.1f  %6.1f", d$TEMP_MAX, d$TEMP_MIN, d$PRECIP), con)
writeLines(":EndMultiData", con)
close(con)
cat("Wrote data/met_daily.rvt:", n, "days,", format(d$date[1]), "to", format(d$date[n]), "\n")

# ---- monthly normals ---------------------------------------------------------
p <- d[d$date >= NORM_START & d$date <= NORM_END, ]
p$month <- as.integer(format(p$date, "%m"))
p$tave  <- (p$TEMP_MAX + p$TEMP_MIN) / 2

# Extraterrestrial radiation Ra (FAO-56 eq. 21), converted to mm/d of evaporation
J     <- as.integer(format(p$date, "%j"))
phi   <- LAT * pi / 180
dr    <- 1 + 0.033 * cos(2 * pi * J / 365)
delta <- 0.409 * sin(2 * pi * J / 365 - 1.39)
ws    <- acos(pmin(pmax(-tan(phi) * tan(delta), -1), 1))
Ra    <- 24 * 60 / pi * 0.0820 * dr *
         (ws * sin(phi) * sin(delta) + cos(phi) * cos(delta) * sin(ws))   # MJ/m2/d
p$pet <- pmax(0, 0.0023 * 0.408 * Ra * (p$tave + 17.8) *
                 sqrt(pmax(p$TEMP_MAX - p$TEMP_MIN, 0)))

nm <- data.frame(month = 1:12,
                 temp_ave_C = round(tapply(p$tave, p$month, mean), 1),
                 pet_mm_d   = round(tapply(p$pet,  p$month, mean), 2),
                 precip_mm_month = round(tapply(p$PRECIP, p$month, sum) /
                                         (length(unique(format(p$date, "%Y"))) - 1), 0))
write.csv(nm, "data/processed/lornex_monthly_normals.csv", row.names = FALSE)
cat("\nMonthly normals", format(NORM_START), "to", format(NORM_END), ":\n")
print(nm, row.names = FALSE)
cat("\nAnnual precip ~", round(sum(p$PRECIP) / as.numeric(NORM_END - NORM_START + 1) * 365.25), "mm/yr\n")
cat("Annual PET    ~", round(sum(p$pet)    / as.numeric(NORM_END - NORM_START + 1) * 365.25), "mm/yr\n")
cat("\n:MonthlyAveTemperature,", paste(sprintf("%5.1f", nm$temp_ave_C), collapse = ", "), "\n")
cat(":MonthlyAveEvaporation,", paste(sprintf("%5.2f", nm$pet_mm_d),   collapse = ", "), "\n")
