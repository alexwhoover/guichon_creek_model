"""Download WSC 08LG056 (Guichon Creek above Tunkwa Lake Diversion) historical daily
mean discharge (HYDAT, via the ECCC GeoMet OGC API) and write:
  data/raw/08LG056_daily_HYDAT.csv  - raw record with HYDAT symbols
  data/obs_flow_08LG056_daily.rvt   - Raven :ObservationData (subbasin 3 = 08LG056, m3/s)

Usage (from Raven/HBVEC_Model):  python3 data/scripts/get_obs_08LG056.py [START_DATE]
START_DATE defaults to 1982-01-01 to match the 08LG041 file (the record starts 1967-10).

08LG056 is a natural-flow reference station (RHBN, 76.06 km2) in the headwaters of
subbasin 1, upstream of the Tunkwa Lake diversion. It is the unregulated calibration target.
"""
import csv, datetime as dt, json, os, sys, urllib.request

STN = "08LG056"
MISSING = -1.2345
START = dt.date.fromisoformat(sys.argv[1]) if len(sys.argv) > 1 else dt.date(1982, 1, 1)
DATA = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # .../data
URL = ("https://api.weather.gc.ca/collections/hydrometric-daily-mean/items"
       f"?STATION_NUMBER={STN}&datetime={START}/..&f=json&limit=10000&sortby=DATE&offset={{}}")
# datetime filter: the API stops paging at 20000 rows, and the full record is longer than that

rows, off = [], 0
while True:
    with urllib.request.urlopen(URL.format(off), timeout=120) as r:
        d = json.load(r)
    rows += [f["properties"] for f in d["features"]]
    off += d["numberReturned"]
    if d["numberReturned"] == 0 or off >= d["numberMatched"]:
        break
rows.sort(key=lambda p: p["DATE"])

with open(os.path.join(DATA, "raw", f"{STN}_daily_HYDAT.csv"), "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["DATE", "DISCHARGE_m3s", "SYMBOL"])
    for p in rows:
        w.writerow([p["DATE"], "" if p["DISCHARGE"] is None else round(p["DISCHARGE"], 4),
                    p["DISCHARGE_SYMBOL_EN"] or ""])

q = {dt.date.fromisoformat(p["DATE"]): p["DISCHARGE"] for p in rows if p["DISCHARGE"] is not None}
end = max(q)
n = (end - START).days + 1
vals = [q.get(START + dt.timedelta(i), MISSING) for i in range(n)]
nmiss = sum(v == MISSING for v in vals)

with open(os.path.join(DATA, "obs_flow_08LG056_daily.rvt"), "w") as fh:
    fh.write(f"# WSC {STN} Guichon Creek above Tunkwa Lake Diversion - daily mean discharge (HYDAT)\n"
             f"# Source: ECCC GeoMet API, collection hydrometric-daily-mean; retrieved {dt.date.today()}\n"
             f"# Gross drainage area 76.06 km2; natural flow (RHBN). Generated by data/scripts/get_obs_08LG056.py\n"
             f"# Record {START} to {end}: {n} days, {nmiss} missing (-1.2345)\n"
             "# Ice-affected (B) and estimated (E) values kept as published; see the CSV for flags.\n"
             ":ObservationData HYDROGRAPH 3 m3/s\n"
             f" {START} 00:00:00  1.0  {n}\n")
    for v in vals:
        fh.write(f"{MISSING}\n" if v == MISSING else f"{v:.4f}\n")
    fh.write(":EndObservationData\n")
print(f"{len(rows)} HYDAT rows; wrote {n} days {START}..{end}, {nmiss} missing")
